def _build_polars_chain(steps: list[TransformStep]) -> list[str]:
    """Build a chained Polars expression from steps.

    Tries to collapse sequential operations into a chain.
    """
    chain_parts: list[str] = []

    for step in steps:
        expr = step.expr.strip()
        # Strip "df = " prefix if present
        if expr.startswith("df = "):
            expr = expr[5:]
        # Strip leading "df." to allow chaining
        if expr.startswith("df."):
            chain_parts.append("." + expr[3:])
        else:
            # Can't chain — starts a new expression
            if chain_parts:
                chain_parts[-1] = chain_parts[-1]  # keep as-is
            chain_parts.append(expr)

    if not chain_parts:
        return ["df"]

    # If all parts are chainable (start with .)
    if all(p.startswith(".") for p in chain_parts):
        result = ["df"]
        result.extend(chain_parts)
        return result

    # Otherwise return as separate assignments
    return [f"df{p}" if p.startswith(".") else p for p in chain_parts]


def _polars_to_sql_steps(
    steps: list[TransformStep], source_ref: str
) -> list[tuple[str, str]]:
    """Best-effort conversion of Polars steps to SQL.

    Returns list of (sql_string, comment) tuples.
    """
    results: list[tuple[str, str]] = []
    prev_ref = source_ref

    for step in steps:
        expr = step.expr.strip()
        desc = step.metadata.get("description", "") if step.metadata else ""

        # Strip df prefix
        if expr.startswith("df = "):
            expr = expr[5:]
        if expr.startswith("df."):
            expr = expr[3:]

        sql = _expr_to_sql(expr, prev_ref)
        if sql:
            results.append((sql, desc))
            prev_ref = f"step_{len(results)}" if len(results) < 20 else prev_ref

    return results


def _expr_to_sql(expr: str, source: str) -> str | None:
    """Convert a single Polars expression to SQL (best effort).

    Returns SQL string or None if not convertible.
    """
    # filter(condition)
    if expr.startswith("filter(") and expr.endswith(")"):
        condition = expr[7:-1]
        sql_cond = _polars_condition_to_sql(condition)
        if sql_cond:
            return f"SELECT * FROM {source} WHERE {sql_cond}"

    # select([...]) or select(...)
    if expr.startswith("select("):
        cols = _extract_column_names(expr)
        if cols:
            return f"SELECT {', '.join(cols)} FROM {source}"

    # unique()
    if expr == "unique()":
        return f"SELECT DISTINCT * FROM {source}"

    # sort(...)
    if expr.startswith("sort("):
        cols = _extract_sort_columns(expr)
        if cols:
            return f"SELECT * FROM {source} ORDER BY {cols}"

    # head(n) / limit
    if expr.startswith("head(") and expr.endswith(")"):
        n = expr[5:-1]
        return f"SELECT * FROM {source} LIMIT {n}"

    # Generic with_columns — add as comment
    if expr.startswith("with_columns("):
        return f"SELECT *, /* {expr} */ FROM {source}"

    # Fallback: wrap in comment
    return f"SELECT * FROM {source} /* polars: {expr} */"


def _polars_condition_to_sql(condition: str) -> str | None:
    """Convert a Polars filter condition to SQL WHERE clause."""
    # pl.col('x') > 5 → x > 5
    import re

    # Simple pl.col('name') op value patterns
    pattern = r"pl\.col\(['\"](\w+)['\"]\)\s*(>|<|>=|<=|==|!=)\s*(.+)"
    match = re.match(pattern, condition.strip())
    if match:
        col, op, val = match.groups()
        sql_op = "=" if op == "==" else ("<>" if op == "!=" else op)
        return f"{col} {sql_op} {val}"

    # pl.col('x').is_not_null()
    pattern_not_null = r"pl\.col\(['\"](\w+)['\"]\)\.is_not_null\(\)"
    match = re.match(pattern_not_null, condition.strip())
    if match:
        return f"{match.group(1)} IS NOT NULL"

    # pl.col('x').is_null()
    pattern_null = r"pl\.col\(['\"](\w+)['\"]\)\.is_null\(\)"
    match = re.match(pattern_null, condition.strip())
    if match:
        return f"{match.group(1)} IS NULL"

    return None


def _extract_column_names(expr: str) -> list[str] | None:
    """Extract column names from a select expression."""
    import re

    # Match quoted column names
    cols = re.findall(r'["\'](\w+)["\']', expr)
    return cols if cols else None


def _extract_sort_columns(expr: str) -> str | None:
    """Extract sort column specification."""
    import re

    # Match sort('col') or sort('col', descending=True)
    cols = re.findall(r'["\'](\w+)["\']', expr)
    if not cols:
        return None
    desc = "descending=True" in expr or "descending = True" in expr
    suffix = " DESC" if desc else ""
    return ", ".join(f"{c}{suffix}" for c in cols)


def _polars_reader(ext: str) -> str:
    """Get the Polars reader function for a file extension."""
    readers = {
        "csv": "pl.read_csv",
        "parquet": "pl.read_parquet",
        "json": "pl.read_json",
        "jsonl": "pl.read_ndjson",
        "ndjson": "pl.read_ndjson",
        "ipc": "pl.read_ipc",
        "avro": "pl.read_avro",
        "xlsx": "pl.read_excel",
        "xls": "pl.read_excel",
    }
    return readers.get(ext, "pl.read_csv")


def _polars_writer(ext: str) -> str:
    """Get the Polars writer method for a file extension."""
    writers = {
        "csv": "write_csv",
        "parquet": "write_parquet",
        "json": "write_json",
        "jsonl": "write_ndjson",
        "ndjson": "write_ndjson",
        "ipc": "write_ipc",
        "avro": "write_avro",
        "xlsx": "write_excel",
    }
    return writers.get(ext, "write_csv")


def _sanitize_name(name: str) -> str:
    """Convert a name to a valid Python identifier."""
    import re

    name = re.sub(r"[^a-zA-Z0-9_]", "_", name)
    name = re.sub(r"_+", "_", name).strip("_").lower()
    if name and name[0].isdigit():
        name = "fn_" + name
    return name or "transform"
