# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------


def _step(expr: str, desc: str = "") -> TransformStep:
    """Create a minimal TransformStep for testing."""
    return TransformStep(
        expr=expr,
        input_hash="abc123",
        output_schema=None,
        metadata={"description": desc} if desc else {},
    )


SAMPLE_STEPS = [
    _step("df.filter(pl.col('age') > 18)", "Filter adults"),
    _step("df.select(['name', 'age'])", "Select columns"),
    _step("df.sort('age')", "Sort by age"),
]


