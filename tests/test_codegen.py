class TestWorkspaceIntegration:
    def test_generate_pipeline_from_workspace(self, tmp_path):
        import polars as pl

        from sweet.core.workspace import Workspace

        # Create a temp CSV
        csv_file = tmp_path / "test.csv"
        df = pl.DataFrame({"name": ["Alice", "Bob"], "age": [30, 17]})
        df.write_csv(csv_file)

        ws = Workspace()
        ws.load(str(csv_file))
        ws.transform("df.filter(pl.col('age') > 18)")

        code = ws.generate_pipeline(format="polars", source=str(csv_file))
        assert "import polars as pl" in code
        assert "def transform(" in code
        assert "filter" in code

    def test_all_formats_produce_output(self, tmp_path):
        import polars as pl

        from sweet.core.workspace import Workspace

        csv_file = tmp_path / "data.csv"
        pl.DataFrame({"x": [1, 2, 3]}).write_csv(csv_file)

        ws = Workspace()
        ws.load(str(csv_file))
        ws.transform("df.filter(pl.col('x') > 1)")

        for fmt in ("polars", "sql", "dbt", "script"):
            code = ws.generate_pipeline(format=fmt)
            assert len(code) > 20, f"Format '{fmt}' produced too little output"
