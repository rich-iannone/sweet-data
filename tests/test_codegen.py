class TestPolarsFormat:
    def test_basic_generation(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars")
        assert "import polars as pl" in code
        assert "def transform(" in code
        assert 'if __name__ == "__main__"' in code

    def test_custom_name(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars", name="clean_data")
        assert "def clean_data(" in code
        assert "clean_data(df)" in code

    def test_source_path(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars", source="data.csv")
        assert 'pl.read_csv("data.csv")' in code
        assert "Source: data.csv" in code

    def test_source_parquet(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars", source="data.parquet")
        assert 'pl.read_parquet("data.parquet")' in code

    def test_output_path(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars", output="out.parquet")
        assert 'write_parquet("out.parquet")' in code

    def test_output_csv(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars", output="out.csv")
        assert 'write_csv("out.csv")' in code

    def test_description(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars", description="My pipeline")
        assert "My pipeline" in code

    def test_empty_steps(self):
        code = generate_pipeline([], format="polars")
        assert "return df" in code
        assert "import polars" in code

    def test_contains_timestamp(self):
        code = generate_pipeline(SAMPLE_STEPS, format="polars")
        assert "Pipeline generated by Sweet on" in code


